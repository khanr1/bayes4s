#!/usr/bin/env python3
"""Turns a plain-text list of private terms into HMAC-SHA-256 digests.

    export BAYES4S_PRIVATE_TERMS_KEY="<a secret phrase, kept outside the repository>"
    python3 scripts/hash-private-terms.py ~/private-terms.txt

One term per line; blank lines and lines starting with `#` are ignored. A single-word line is
recorded as that word. A multi-word line is recorded whole and as pairs of consecutive words, but
not word by word: an ordinary word of a name ("group", "industries") would otherwise fail CI
everywhere. To refuse a single word, give it its own line.

The output replaces `.private-terms.sha256`, the only one of the two files that belongs in the
repository. The script prints counts only, never a term and never the key.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from private_terms import DIGEST_FILE, KEY_ENV, digest, load_key, normalise  # noqa: E402


def main() -> int:
    parser = argparse.ArgumentParser(description="Hash a plain-text private-term list.")
    parser.add_argument("terms", help="file with one term per line, kept OUTSIDE the repository")
    parser.add_argument("--key-file", help=f"file holding the HMAC key (default: ${KEY_ENV})")
    parser.add_argument("--out", default=DIGEST_FILE, help=f"output file (default: {DIGEST_FILE})")
    args = parser.parse_args()

    key = load_key(args.key_file)
    if key is None:
        print(f"no HMAC key: set ${KEY_ENV} or pass --key-file", file=sys.stderr)
        return 2

    source = Path(args.terms)
    if not source.is_file():
        print("the term list was not found (it must live outside the repository)", file=sys.stderr)
        return 2

    entries: set[str] = set()
    lines = 0
    for line in source.read_text(encoding="utf-8").splitlines():
        term = line.strip()
        if not term or term.startswith("#"):
            continue
        lines += 1
        words = normalise(term)
        if not words:
            continue
        entries.add(" ".join(words))
        if len(words) == 1:
            entries.update(words)
        else:
            # One word of a compound name is not necessarily private ("industries", "group"),
            # so only the whole term and its consecutive pairs are recorded. To refuse a single
            # word, it needs its own line in the list.
            entries.update(f"{a} {b}" for a, b in zip(words, words[1:]))

    out = Path(args.out)
    body = "\n".join(sorted(digest(e, key) for e in entries))
    out.write_text(
        "# HMAC-SHA-256 of the private terms, salted with a key kept outside this repository.\n"
        "# Generated by scripts/hash-private-terms.py; the plain-text list is never committed.\n"
        f"{body}\n",
        encoding="utf-8",
    )
    print(f"{lines} terms read, {len(entries)} digests written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
